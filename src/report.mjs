import { SEVERITIES } from './rules.mjs';

const ICON = { critical: '🔴', high: '🟠', medium: '🟡', low: '⚪' };
const LABEL = { critical: 'Critical: fix before anyone else uses the app', high: 'High: fix before launch', medium: 'Medium: fix soon', low: 'Low: good hygiene' };
const loc = (f) => (f.file ? `\`${f.file}${f.line ? `:${f.line}` : ''}\`` : 'project-wide');

export function counts(findings) { return Object.fromEntries(SEVERITIES.map((s) => [s, findings.filter((f) => f.severity === s).length])); }

export function toMarkdown(r) {
  const c = counts(r.findings);
  const L = [];
  L.push(`# Security review: ${r.name}`, '');
  L.push(`**Score: ${r.score}/100 (grade ${r.grade})**: ${c.critical} critical · ${c.high} high · ${c.medium} medium · ${c.low} low`, '');
  L.push(`Scanned ${r.filesScanned} files on ${r.date}. Read-only: nothing was changed and no secret values are shown in this report.`, '');
  if (!r.findings.length) L.push('No issues found by the automatic checks. That is a good sign, not a guarantee: see "What this review can\'t see" below.', '');
  for (const sev of SEVERITIES) {
    const list = r.findings.filter((f) => f.severity === sev);
    if (!list.length) continue;
    L.push(`## ${ICON[sev]} ${LABEL[sev]} (${list.length})`, '');
    list.forEach((f, i) => {
      L.push(`### ${i + 1}. ${f.title}`, '', `- **Where:** ${loc(f)}`, `- **Why it matters:** ${f.why}`, `- **Fix:** ${f.fix}`, `- Check: \`${f.id}\``, '');
    });
  }
  if (r.audit) {
    L.push('## Dependency audit (npm audit)', '');
    if (r.audit.error) L.push(`Skipped: ${r.audit.error}.`, '');
    else {
      const a = r.audit.counts;
      L.push(`${a.critical} critical · ${a.high} high · ${a.moderate} moderate · ${a.low} low (production dependencies).`, '');
      for (const t of r.audit.top) L.push(`- \`${t.name}\`: ${t.severity}, ${t.fix}`);
      L.push('', 'Run `npm audit fix` and re-test; read the changelog before any major-version bump.', '');
    }
  }
  L.push('## What this review can\'t see', '');
  L.push('These checks read your code. They can\'t see your live configuration, so also check:', '');
  L.push('- Supabase dashboard: RLS on every table *in production*, auth settings (email confirmation, leaked-password protection), storage bucket privacy.');
  L.push('- Your host: which environment variables are set where, preview deployments that are public, old deployments still online.');
  L.push('- Business logic: can user A see or edit user B\'s data by changing an ID in the URL? Test it with two accounts.');
  L.push('- Spend caps on OpenAI/Anthropic, Stripe, email and hosting accounts.', '');
  L.push('## Going to production? What this doesn\'t cover', '');
  L.push('A scanner finds the common, obvious mistakes. A real launch also needs: a manual review of auth and data access paths, testing with real accounts and roles, secret rotation and history cleanup, WAF and bot protection, backups you have actually restored, monitoring and alerting, and load and cost testing.', '');
  L.push('Want a senior team to check it before real users arrive? Free assessment at https://blitzhash.com', '');
  L.push('---', '_Generated by [BlitzHash Security Review](https://github.com/blitzhash360-web/blitzhash-security-review). Heuristic checks: confirm each finding before acting on it._', '');
  return L.join('\n');
}

const C = { critical: '\x1b[41;97m', high: '\x1b[31m', medium: '\x1b[33m', low: '\x1b[90m', bold: '\x1b[1m', dim: '\x1b[2m', reset: '\x1b[0m', green: '\x1b[32m' };
export function toTerminal(r, color = true) {
  const k = (code, s) => (color ? `${C[code]}${s}${C.reset}` : s);
  const c = counts(r.findings);
  const L = [];
  L.push(k('bold', `BlitzHash Security Review: ${r.name}`));
  L.push(`${k('bold', `Score ${r.score}/100 (${r.grade})`)}  ${k('critical', ` ${c.critical} CRITICAL `)} ${k('high', `${c.high} high`)} ${k('medium', `${c.medium} medium`)} ${k('low', `${c.low} low`)}`);
  L.push(k('dim', `${r.filesScanned} files scanned · read-only · secret values never printed`), '');
  for (const f of r.findings.slice(0, r.limit || 50)) {
    L.push(`${k(f.severity, f.severity.toUpperCase().padEnd(8))} ${f.title}`);
    L.push(`         ${k('dim', `${f.file ? f.file + (f.line ? ':' + f.line : '') : 'project-wide'}  ·  ${f.id}`)}`);
    L.push(`         ${k('green', 'fix:')} ${f.fix}`);
  }
  if (r.findings.length > (r.limit || 50)) L.push(k('dim', `… ${r.findings.length - (r.limit || 50)} more in the full report (--out SECURITY-REVIEW.md)`));
  if (!r.findings.length) L.push(k('green', 'No issues found by the automatic checks.'));
  L.push('', k('dim', 'Going to production? Free senior review: https://blitzhash.com'));
  return L.join('\n');
}
